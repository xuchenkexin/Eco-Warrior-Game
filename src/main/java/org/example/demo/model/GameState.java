package org.example.demo.model;

/**
 * Defines different game states
 */
public enum GameState {
    TITLE_SCREEN,  // Title screen
    PLAYING,       // Game in progress
    PAUSED,        // Game paused
    DIALOG,        // Dialog state
    CHALLENGE,     // Challenge state
    LEVEL_COMPLETE, // Level completed
    GAME_OVER      // Game over
} 