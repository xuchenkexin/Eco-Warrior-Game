package org.example.demo.model;

/**
 * Defines item types in the game
 */
public enum ItemType {
    SEED,      // Seeds for planting trees
    SOIL,      // Soil for planting
    GROWN_SEED,// A seed that has grown
    TOOL,      // Tools for various eco-friendly operations
    RELIC,     // Natural relics, collect four to summon the Sky Dragon
    WASTE,     // Waste that needs recycling
    PLASTIC,   // Plastic waste
    METAL,     // Metal waste
    ORGANIC    // Organic waste
} 